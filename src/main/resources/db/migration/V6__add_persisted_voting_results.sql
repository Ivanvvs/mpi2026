CREATE TABLE voting_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voting_id BIGINT NOT NULL,
    option_id BIGINT NOT NULL,
    votes_count BIGINT NOT NULL,
    calculated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_voting_result_option UNIQUE (voting_id, option_id),
    CONSTRAINT fk_voting_results_voting FOREIGN KEY (voting_id) REFERENCES secret_votings (id),
    CONSTRAINT fk_voting_results_option FOREIGN KEY (option_id) REFERENCES voting_options (id)
);

CREATE INDEX idx_voting_results_voting_id ON voting_results (voting_id);
